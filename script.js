/* ==========================================================
   SCROLL REVEAL
   ========================================================== */
const revealEls = document.querySelectorAll('.reveal, .reveal-avatar');
const revealObserver = new IntersectionObserver((entries)=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){
      entry.target.classList.add('in-view');
      revealObserver.unobserve(entry.target);
    }
  });
},{threshold:0.15});
revealEls.forEach(el=>revealObserver.observe(el));

/* ==========================================================
   MIXING CONSOLE — animate channel fills into view
   ========================================================== */
const channels = document.querySelectorAll('.channel');
const consoleObserver = new IntersectionObserver((entries)=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){
      const level = entry.target.getAttribute('data-level');
      const fill = entry.target.querySelector('.channel-fill');
      const cap = entry.target.querySelector('.channel-cap');
      fill.style.height = level + '%';
      cap.style.bottom = level + '%';
      consoleObserver.unobserve(entry.target);
    }
  });
},{threshold:0.4});
channels.forEach(c=>consoleObserver.observe(c));

/* ==========================================================
   STAT COUNTERS
   ========================================================== */
const statNums = document.querySelectorAll('.stat-num');
const statObserver = new IntersectionObserver((entries)=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){
      const el = entry.target;
      const target = parseInt(el.getAttribute('data-count'), 10);
      let current = 0;
      const duration = 1400;
      const start = performance.now();
      function step(now){
        const progress = Math.min((now - start) / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        current = Math.round(target * eased);
        el.textContent = current;
        if(progress < 1) requestAnimationFrame(step);
      }
      requestAnimationFrame(step);
      statObserver.unobserve(el);
    }
  });
},{threshold:0.5});
statNums.forEach(el=>statObserver.observe(el));

